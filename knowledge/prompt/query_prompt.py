"""查询相关提示词模板（旅游领域）"""

# ------------------------------------------------------------ #
# 1) 实体提取 + 查询改写（目的地/内容类型识别，含多轮指代消解）
# ------------------------------------------------------------ #
ENTITY_EXTRACT_SYSTEM_PROMPT = """你是一名旅游知识助手，擅长从用户问题中识别旅游目的地与内容意图。

你的任务是输出 JSON，不要输出任何多余文字：
{
  "region": "目的地/城市，如 三亚、云南、厦门、张家界、成都、杭州；无法确定则为空字符串",
  "content_type": "内容类型，只能取：景点介绍 / 线路推荐 / 酒店信息 / 美食推荐 / 交通指南 / 文化民俗 之一；无法确定则为空字符串",
  "rewritten_query": "把用户问题改写成包含目的地的独立完整问题，去除口语与代词"
}"""

ENTITY_EXTRACT_TEMPLATE = """【历史对话】
{history_text}

【当前用户问题】
{query}

请结合历史判断用户询问的旅游目的地与内容类型。
- 若用户用"这里/那里/它/上面说的"等代词，需结合历史对话还原具体目的地。
- content_type 依据问题意图判断，例如：问"必去景点/怎么玩/推荐景区"→景点介绍；"行程/线路/几天"→线路推荐；"住哪/酒店/民宿"→酒店信息；"吃什么/美食/餐厅"→美食推荐；"怎么去/交通/机场"→交通指南。

只输出 JSON：
{{
  "region": "",
  "content_type": "",
  "rewritten_query": ""
}}"""

# ------------------------------------------------------------ #
# 2) HyDE：先生成一段"假想攻略"再检索，提升召回
# ------------------------------------------------------------ #
HYDE_USER_PROMPT_TEMPLATE = """请针对以下旅游问题，撰写一段实用的旅游攻略/知识片段（200-300字），风格像景区介绍或出行贴士。
目的地：{region}
问题：{rewritten_query}

要求：内容具体、可直接作为知识库检索答案片段，覆盖要点与实用提示。"""

# ------------------------------------------------------------ #
